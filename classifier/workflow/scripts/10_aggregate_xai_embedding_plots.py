    n_cols = len(available)
    fig_width = max(5.9 * n_cols + 1.3, 8.0)
    fig_height = 5.8
    fig, axes = plt.subplots(1, n_cols, figsize=(fig_width, fig_height), squeeze=False)
    axes = axes[0]

