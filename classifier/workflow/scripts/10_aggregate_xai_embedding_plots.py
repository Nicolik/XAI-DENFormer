def _save_across_splits_fold_grid_method_panel(model_dir, experiment_dirs, method, method_label, subset, output_dir, dpi, overwrite):
    """Save one grid per reduction method: rows are split strategies, columns are folds.

    Uses a fixed six-column layout so panels remain square/readable.
    Rows with five folds leave the last column empty; the legend is placed in
    this bottom-right empty space rather than outside the figure.
    """
    row_entries = []
    for exp_dir in experiment_dirs:
        fold_entries = _build_fold_plot_entries(
            exp_dir,
            method,
            subset,
            combine_geographical_small_folds=False,
        )
        if fold_entries:
            row_entries.append((exp_dir, fold_entries))

    if not row_entries:
        print(f'[WARN] No fold-level {method_label} CSVs found for across-split grid in {model_dir}')
        return []

    out_path = output_dir / f'{method}_embeddings_{subset}_fold_grid_across_split_strategies.png'
    if out_path.exists() and not overwrite:
        print(f'[SKIP] Existing file: {out_path}')
        return [out_path]

    n_rows = len(row_entries)
    max_cols = max(6, max(len(fold_entries) for _, fold_entries in row_entries))

    panel_size = 3.85
    fig_width = panel_size * max_cols + 0.95
    fig_height = panel_size * n_rows + 0.65
    fig, axes = plt.subplots(n_rows, max_cols, figsize=(fig_width, fig_height), squeeze=False)

    legend_ax = None
    for row, (exp_dir, fold_entries) in enumerate(row_entries):
        exp_label = _display_experiment_name(exp_dir)
        for col in range(max_cols):
            ax = axes[row, col]
            if col >= len(fold_entries):
                ax.axis('off')
                # Prefer the empty bottom-right cell, which exists for the
                # temporal/CD-HIT rows, for a compact internal legend.
                if row == n_rows - 1 and col == max_cols - 1:
                    legend_ax = ax
                continue

            entry = fold_entries[col]
            _plot_fold_entry_on_axis(
                ax,
                entry,
                method_label,
                show_xlabel=(row == n_rows - 1),
                show_ylabel=(col == 0),
            )

            if col == 0:
                ax.annotate(
                    exp_label,
                    xy=(-0.42, 0.5),
                    xycoords='axes fraction',
                    rotation=90,
                    ha='center',
                    va='center',
                    fontsize=PANEL_TITLE_FONTSIZE,
                    fontweight='bold',
                )

    if legend_ax is None:
        _add_legend(fig)
        right = 0.905
    else:
        _add_legend_in_axis(legend_ax)
        right = 0.990

    model_label = _display_model_name(model_dir)
    fig.suptitle(model_label, fontsize=TITLE_FONTSIZE, y=0.995)
    fig.subplots_adjust(left=0.075, right=right, bottom=0.070, top=0.935, wspace=0.28, hspace=0.42)
    fig.savefig(out_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)
    print(f'[OK] Saved {out_path}')
    return [out_path]

def _save_across_splits_full_fold_grid(model_dir, experiment_dirs, subset, output_dir, dpi, overwrite):
    """Save a larger grid with one block per split strategy and rows for PCA/t-SNE/UMAP.

    Uses a fixed six-column layout to keep panels square and consistent with
    the single-method across-split grids.
    """
    exp_entries = []
    for exp_dir in experiment_dirs:
        method_entries = []
        for method, method_label in METHODS:
            entries = _build_fold_plot_entries(
                exp_dir,
                method,
                subset,
                combine_geographical_small_folds=False,
            )
            method_entries.append((method, method_label, entries))
        if any(entries for _, _, entries in method_entries):
            exp_entries.append((exp_dir, method_entries))

    if not exp_entries:
        print(f'[WARN] No fold-level projection CSVs found for full across-split grid in {model_dir}')
        return []

    out_path = output_dir / f'full_embeddings_{subset}_fold_grid_across_split_strategies.png'
    if out_path.exists() and not overwrite:
        print(f'[SKIP] Existing file: {out_path}')
        return [out_path]

    n_method_rows = len(METHODS)
    n_exp = len(exp_entries)
    n_rows = n_exp * n_method_rows
    max_cols = 6

    panel_size = 3.55
    fig_width = panel_size * max_cols + 0.95
    fig_height = panel_size * n_rows + 0.8
    fig, axes = plt.subplots(n_rows, max_cols, figsize=(fig_width, fig_height), squeeze=False)

    legend_ax = None
    for exp_idx, (exp_dir, method_entries) in enumerate(exp_entries):
        exp_label = _display_experiment_name(exp_dir)
        for method_idx, (_method, method_label, fold_entries) in enumerate(method_entries):
            row = exp_idx * n_method_rows + method_idx
            for col in range(max_cols):
                ax = axes[row, col]
                if col >= len(fold_entries):
                    ax.axis('off')
                    if row == n_rows - 1 and col == max_cols - 1:
                        legend_ax = ax
                    continue

                entry = fold_entries[col]
                _plot_fold_entry_on_axis(
                    ax,
                    entry,
                    method_label,
                    show_xlabel=(row == n_rows - 1),
                    show_ylabel=(col == 0),
                    title=entry['label'] if method_idx == 0 else '',
                )

                if col == 0:
                    label = f'{exp_label}\n{method_label}' if method_idx == 0 else method_label
                    ax.annotate(
                        label,
                        xy=(-0.42, 0.5),
                        xycoords='axes fraction',
                        rotation=90,
                        ha='center',
                        va='center',
                        fontsize=PANEL_TITLE_FONTSIZE,
                        fontweight='bold' if method_idx == 0 else 'normal',
                    )

    if legend_ax is None:
        _add_legend(fig)
        right = 0.905
    else:
        _add_legend_in_axis(legend_ax)
        right = 0.990

    model_label = _display_model_name(model_dir)
    fig.suptitle(model_label, fontsize=TITLE_FONTSIZE, y=0.996)
    fig.subplots_adjust(left=0.075, right=right, bottom=0.045, top=0.965, wspace=0.28, hspace=0.38)
    fig.savefig(out_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)
    print(f'[OK] Saved {out_path}')
    return [out_path]

def aggregate_across_splits_for_model(model_dir, subset, dpi, overwrite, make_fold_grid=True):
    model_dir = Path(model_dir)
    experiment_dirs = [
        model_dir / exp_name
        for exp_name in EXPERIMENT_ORDER
        if (model_dir / exp_name).is_dir()
    ]

    # Include any unexpected experiment folders after the canonical order.
    known = {p.resolve() for p in experiment_dirs}
    for exp_dir in _find_experiment_dirs_for_model(model_dir):
        if exp_dir.resolve() not in known:
            experiment_dirs.append(exp_dir)

    if not experiment_dirs:
        print(f'[WARN] No split-strategy directories found in {model_dir}')
        return []

    output_dir = model_dir / ACROSS_SPLITS_OUTPUT_DIR_NAME
    output_dir.mkdir(parents=True, exist_ok=True)

    saved = []
    for method, method_label in METHODS:
        saved.extend(
            _save_across_splits_method_panel(
                model_dir=model_dir,
                experiment_dirs=experiment_dirs,
                method=method,
                method_label=method_label,
                subset=subset,
                output_dir=output_dir,
                dpi=dpi,
                overwrite=overwrite,
            )
        )

    if make_fold_grid:
        for method, method_label in METHODS:
            saved.extend(
                _save_across_splits_fold_grid_method_panel(
                    model_dir=model_dir,
                    experiment_dirs=experiment_dirs,
                    method=method,
                    method_label=method_label,
                    subset=subset,
                    output_dir=output_dir,
                    dpi=dpi,
                    overwrite=overwrite,
                )
            )
        saved.extend(
            _save_across_splits_full_fold_grid(
                model_dir=model_dir,
                experiment_dirs=experiment_dirs,
                subset=subset,
                output_dir=output_dir,
                dpi=dpi,
                overwrite=overwrite,
            )
        )

    summary_path = output_dir / f'across_split_embedding_plot_summary_{subset}.csv'
    rows = []
    for exp_dir in experiment_dirs:
        row = {
            'experiment_dir': str(exp_dir),
            'split_strategy': _display_experiment_name(exp_dir),
        }
        fold_dirs = _find_split_dirs(exp_dir, subset)
        row['n_folds'] = len(fold_dirs)
        row['folds'] = ';'.join(_display_fold_name(split_dir) for split_dir in fold_dirs)
        for method, _ in METHODS:
            csv_path = _find_dataset_projection_path(exp_dir, method, subset)
            row[f'{method}_csv'] = str(csv_path) if csv_path is not None else ''
            row[f'{method}_exists'] = bool(csv_path is not None and csv_path.exists())
            fold_entries = _available_fold_csvs_for_experiment(exp_dir, method, subset)
            row[f'{method}_n_fold_csv'] = len(fold_entries)
        rows.append(row)
    pd.DataFrame(rows).to_csv(summary_path, index=False)
    print(f'[OK] Saved {summary_path}')
    return saved


def aggregate_one_dir(xai_plot_dir, subset, dpi, max_cols, overwrite):
    xai_plot_dir = Path(xai_plot_dir)
    split_dirs = _find_split_dirs(xai_plot_dir, subset)
    if not split_dirs:
        print(f'[WARN] No split_* projection dirs found in {xai_plot_dir} for subset={subset}')
        return []

    output_dir = xai_plot_dir / OUTPUT_DIR_NAME
    output_dir.mkdir(parents=True, exist_ok=True)

    saved = []
    chunks = _chunked(split_dirs, max_cols)
    multi_chunk = len(chunks) > 1

    for chunk_idx, chunk in enumerate(chunks, start=1):
        suffix = f'_part{chunk_idx:02d}' if multi_chunk else ''
        for method, method_label in METHODS:
            saved.extend(
                _save_method_panel(
                    xai_plot_dir=xai_plot_dir,
                    split_dirs=chunk,
                    method=method,
                    method_label=method_label,
                    subset=subset,
                    output_dir=output_dir,
                    dpi=dpi,
                    overwrite=overwrite,
                    suffix=suffix,
                )
            )
        saved.extend(
            _save_full_panel(
                xai_plot_dir=xai_plot_dir,
                split_dirs=chunk,
                subset=subset,
                output_dir=output_dir,
                dpi=dpi,
                overwrite=overwrite,
                suffix=suffix,
            )
        )

    summary_path = output_dir / f'per_fold_embedding_plot_summary_{subset}.csv'
    summary_rows = []
    for split_dir in split_dirs:
        row = {'split_dir': str(split_dir), 'fold': _display_fold_name(split_dir)}
        for method, _ in METHODS:
            row[f'{method}_csv'] = str(_method_csv_path(split_dir, method, subset))
            row[f'{method}_exists'] = _method_csv_path(split_dir, method, subset).exists()
        summary_rows.append(row)
    pd.DataFrame(summary_rows).to_csv(summary_path, index=False)
    print(f'[OK] Saved {summary_path}')
    return saved


def main():
    args = parse_args()

    total_saved = 0
    model_dirs = set()

    if args.xai_plot_dir:
        input_dir = Path(args.xai_plot_dir)
        if _is_model_dir(input_dir):
            xai_dirs = []
            model_dirs.add(input_dir)
            for exp_name in EXPERIMENT_ORDER:
                exp_dir = input_dir / exp_name
                if exp_dir.is_dir():
                    xai_dirs.append(exp_dir)
            for exp_dir in _find_experiment_dirs_for_model(input_dir):
                if exp_dir not in xai_dirs:
                    xai_dirs.append(exp_dir)
        else:
            xai_dirs = [input_dir]
            model_dirs.add(input_dir.parent)
    else:
        root = Path(args.root) if args.root else _default_root()
        xai_dirs = _find_candidate_dirs(root, args.model_filter)
        model_dirs.update({xai_dir.parent for xai_dir in xai_dirs})
        model_dirs.update(_find_model_dirs(root, args.model_filter))

    if not xai_dirs and not model_dirs:
        print('[WARN] No candidate XAI embedding plot directories found.')
        return

    if not args.skip_per_fold:
        print(f'Found {len(xai_dirs)} candidate fold-level XAI embedding plot directories.')
        for xai_dir in xai_dirs:
            print(f'\n==== Aggregating folds: {xai_dir} ====')
            saved = aggregate_one_dir(
                xai_plot_dir=xai_dir,
                subset=args.subset,
                dpi=args.dpi,
                max_cols=args.max_cols,
                overwrite=args.overwrite,
            )
            total_saved += len(saved)

    if not args.skip_across_splits:
        model_dirs = sorted(model_dirs)
        print(f'\nFound {len(model_dirs)} candidate model directories for across-split panels.')
        for model_dir in model_dirs:
            print(f'\n==== Aggregating split strategies: {model_dir} ====')
            saved = aggregate_across_splits_for_model(
                model_dir=model_dir,
                subset=args.subset,
                dpi=args.dpi,
                overwrite=args.overwrite,
                make_fold_grid=not args.skip_across_split_fold_grid,
            )
            total_saved += len(saved)

    print(f'\nDone. Saved or found {total_saved} aggregate panel file(s).')


if __name__ == '__main__':
    main()
