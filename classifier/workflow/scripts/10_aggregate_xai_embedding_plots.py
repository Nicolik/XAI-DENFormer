    if not available:
        print(f'[WARN] No dataset-level {method_label} CSVs found in {model_dir}')
        return []

    out_path = output_dir / f'{method}_embeddings_{subset}_across_split_strategies.png'
    if out_path.exists() and not overwrite:
        print(f'[SKIP] Existing file: {out_path}')
